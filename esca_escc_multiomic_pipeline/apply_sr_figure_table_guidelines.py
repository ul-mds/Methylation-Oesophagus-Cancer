def _clear_runs(p: DocxParagraph) -> None:
    for run in list(p.runs):
        run._element.getparent().remove(run._element)


def _set_figure_legend_paragraph(p: DocxParagraph, n: int, body: str) -> None:
    _clear_runs(p)
    head = p.add_run(f"Figure {n}. ")
    head.bold = True
    parts = re.split(r"(\*\*[a-z](?:–[a-z]+)?\*\*,\s*)", body)
    for part in parts:
        if not part:
            continue
        m = re.match(r"\*\*([a-z](?:–[a-z]+)?)\*\*,\s*", part)
        if m:
            r = p.add_run(f"{m.group(1)}, ")
            r.bold = True
        else:
            p.add_run(part)


def _legend_already_expanded(doc: Document) -> bool:
    past = False
    f1_ok = False
    f2_ok = False
    f3_ok = False
    f4_ok = False
    f5_ok = False
    f6_ok = False
    for p in doc.paragraphs:
        t = p.text.strip()
        if t == "Figure legends":
            past = True
            continue
        if past and t.startswith("Supplementary"):
            break
        if not past:
            continue
        if t.startswith("Figure 1."):
            f1_ok = LEGEND_IDEMPOTENCY_PHRASE in t
        elif t.startswith("Figure 2."):
            f2_ok = LEGEND2_IDEMPOTENCY_PHRASE in t
        elif t.startswith("Figure 3."):
            f3_ok = LEGEND3_IDEMPOTENCY_PHRASE in t
        elif t.startswith("Figure 4."):
            f4_ok = LEGEND4_IDEMPOTENCY_PHRASE in t
        elif t.startswith("Figure 5."):
            f5_ok = LEGEND5_IDEMPOTENCY_PHRASE in t
        elif t.startswith("Figure 6."):
            f6_ok = LEGEND6_IDEMPOTENCY_PHRASE in t
    return f1_ok and f2_ok and f3_ok and f4_ok and f5_ok and f6_ok


def _apply_figure_legends(doc: Document) -> None:
    if _legend_already_expanded(doc):
        print("Figure legends already expanded; skipping.")
        return
    past = False
    for p in doc.paragraphs:
        t = p.text.strip()
        if t == "Figure legends":
            past = True
            continue
        if past and t.startswith("Supplementary"):
            break
        m = re.match(r"^Figure (\d+)\.", t)
        if not m:
            continue
        n = int(m.group(1))
        if n not in LEGENDS_300:
            continue
        body = LEGENDS_300[n]
        flat = f"Figure {n}. " + re.sub(r"\*\*([a-z](?:–[a-z]+)?)\*\*,\s*", r"\1, ", body)
        wc = len(flat.split())
        if wc > 120:
            raise RuntimeError(f"Figure {n} legend exceeds 120 words ({wc}); expected ~50.")
        _set_figure_legend_paragraph(p, n, body)
        print(f"Figure {n} legend words (approx): {wc}")


def _insert_paragraph_after_element(element, doc: Document) -> DocxParagraph:
    new_el = OxmlElement("w:p")
    element.addnext(new_el)
    return DocxParagraph(new_el, doc._body)


def _table_index_from_caption(doc: Document) -> dict[int, int]:
    """Map table number N -> caption starts with 'Table N.' using document order."""
    mapping: dict[int, int] = {}
    for i, p in enumerate(doc.paragraphs):
        m = re.match(r"^Table (\d+)\.", p.text.strip())
        if m:
            mapping[int(m.group(1))] = i
    return mapping


def _apply_table_notes(doc: Document) -> None:
    body = doc.element.body
    children = list(body)
    tbl_positions: list[tuple[int, object]] = []
    for idx, el in enumerate(children):
        if el.tag.endswith("}tbl"):
            tbl_positions.append((idx, el))

    if len(tbl_positions) != len(doc.tables):
        print("Warning: XML table count mismatch with doc.tables; skipping table notes.")
        return

    cap_map = _table_index_from_caption(doc)
    for ti, tbl in enumerate(doc.tables):
        tbl_el = tbl._element
        nxt = tbl_el.getnext()
        if nxt is not None and nxt.tag.endswith("}p"):
            tp = DocxParagraph(nxt, doc._body)
            if tp.text.strip().startswith("Note."):
                continue
        n = ti + 1
        note = TABLE_NOTES.get(n)
        if not note:
            continue
        np = _insert_paragraph_after_element(tbl_el, doc)
        np.style = doc.styles["Normal"]
        np.add_run(note)
        print(f"Inserted note after Table {n}.")


def _apply_acknowledgements(doc: Document) -> None:
    for p in doc.paragraphs:
        if p.text.strip().startswith("The authors thank the TCGA"):
            if "matplotlib" in p.text:
                return
            p.add_run(ACK_APPEND)
            print("Acknowledgements appended (figures/software).")
            return


def main() -> None:
    path = Path(__file__).resolve().parents[1] / DOC_NAME
    doc = Document(str(path))
    _apply_figure_legends(doc)
    _apply_table_notes(doc)
    _apply_acknowledgements(doc)
    doc.save(str(path))
    print("Saved:", path)


if __name__ == "__main__":
    main()
